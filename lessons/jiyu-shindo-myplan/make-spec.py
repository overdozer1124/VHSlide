for lesson, prefix in ((kokugo, "jp"), (sansu, "ma")):
    for P in lesson["phases"]:
        if P["name"].startswith("ミッション"):
            n = P["name"].replace("ミッション", "")
            P["slides"][0].setdefault("id", f"{prefix}-m{n}")
            if P["slides"][0].get("id_", 1) is None:
                P["slides"][0].pop("id_")
    for P in lesson["phases"]:
        for S in P["slides"]:
            S.pop("id_", None)
            if S.get("hints") is None and "hints" in S:
                S.pop("hints")
                S.pop("hintsTitle", None)


