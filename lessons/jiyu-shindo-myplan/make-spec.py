def mission_map(prefix, title, goal, rows, place_note):
    """Learning map page: one button row per mission (links to that mission's first page)."""
    items = [{"type": "card", "x": 36, "y": 100, "w": 888, "h": 50, "text": goal, "tone": "accent", "fontSize": 16, "valign": "middle"},
             {"type": "text", "x": 820, "y": 150, "w": 104, "h": 20, "text": "できたら✓", "fontSize": 12, "color": "sub", "align": "center"}]
    top = 172
    bottom = 510
    n = len(rows)
    h = (bottom - top) / n - 6
    for i, (label, text, hint, place, target) in enumerate(rows):
        y = top + i * (h + 6)
        items += [
            {"type": "shape", "shape": "rounded", "x": 36, "y": y, "w": 150, "h": h, "fill": "accent" if i == 0 else "primary",
             "stroke": "#ffffff", "text": label, "color": "#ffffff", "fontSize": 15, "pad": [0.05, 0.1, 0.05, 0.1], "link": target},
            {"type": "shape", "shape": "rounded", "x": 196, "y": y, "w": 404, "h": h, "fill": "surface", "stroke": "line",
             "text": text, "fontSize": 15, "align": "left", "bold": False, "pad": [0.03, 0.1, 0.03, 0.1], "link": target},
            {"type": "text", "x": 606, "y": y, "w": 92, "h": h, "text": hint, "fontSize": 13, "color": "sub"},
            {"type": "text", "x": 700, "y": y, "w": 116, "h": h, "text": place, "fontSize": 12, "color": "sub"},
            {"type": "field", "x": 820, "y": y, "w": 104, "h": h, "fontSize": 12,
             "field": {"id": f"done-{target}", "type": "checkbox", "label": "完了"}},
        ]
    return {"kind": "form", "id": f"{prefix}-map", "tag": "学習マップ", "heading": title, "mapButton": False,
            "buttons": [{"text": "マイプランシートへ", "to": "plan", "w": 170}], "items": items,
            "notes": f"どのミッションも、左の四角を押すとそのページへ移動できる。各ページ右上の「学習マップへ」で戻る。\n{place_note}"}


def mission(n, heading, prompt, hints, fields, notes, tag=None, hints_title="ヒント", share=None, extra=None):
    s = {"kind": "question", "tag": tag or f"ミッション{n}", "heading": heading, "prompt": prompt,
         "hintsTitle": hints_title, "hints": hints, "fields": fields, "notes": notes}
    if len(fields) > 1:
        s.update({"stack": True, "share": share or [0.5, 0.5]})
    if extra:
        s.update(extra)
    return s


